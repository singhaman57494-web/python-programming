# Dictonary:- 
'''
1. Dictionaries are used to store data values in key:value pairs.

2. they are unordered, mutable(changeable) & don't allow duplicate keys.

'''
# Example:-

dict = {
    "name" : "shradha", # key:values
    "cgpa" : 9.6,
    "marks" : [98 , 97, 95],
}
print(type(dict))  # type of dictionary
print(dict)        # print dictionary
print(dict["name"])   #print first key