#                    string function in python language


str = "i am a coder."

# endswith function ()

print(str.endswith("er.")) # returns True if string ends with substr

# capitalize function ()

print(str.capitalize()) # capitalizes 1st char

# replace function()

print(str.replace("coder", "student")) # replaces all occurrences of old

# find function()

print(str.find("am")) # return 1st index of 1st occurrer

# count function()

print(str.count("a")) # count the occurrence of substring.