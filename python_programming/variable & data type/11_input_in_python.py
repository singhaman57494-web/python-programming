#                                 input in python

'''
input() statement is use to accept values (using keyboard) from user.

1. input()   #result for input() is always a str.

2. int(input())  # integer value.

3.float(input()) # float value

'''

#                            str input

name = input("enter your name : ")
print(name)


#                          integer input

age = int(input("enter your age : "))
print(age)

#                          float input 

price = float(input("enter the price of ball : "))
print(price)