#                      list in python programming 

# what is list ?
'''
1. a built in data type that stores set of values.
2. it can store elements of different types (integer, float, string, etc).
3. list is mutable in python.

'''
# example;-

fruits = ["apple", "banana", "mango"]
print(fruits)  # print list
print(type(fruits)) # print type of list
print(fruits[0]) # print first element of list
print(len(fruits)) # print lenth of list

#list is mutable in python 
student = ["aman" , 84.26 , 22 , "delhi" ]
print(student)

student[0] = "aman chauhan"
print(student) # list is mutable